export type Copy = typeof tr;

const dictionaries: Record<Locale, Copy> = { tr, en };

export function copy(locale: Locale = DEFAULT_LOCALE): Copy {
  return dictionaries[locale];
}

export function fill(template: string, params: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ""));
}

export function term(locale: Locale, group: "categories" | "prohibitions" | "ai" | "channels" | "territories" | "statuses" | "pricingModes", id: string): string {
  const table = copy(locale)[group] as Record<string, string>;
  return table[id] ?? id.replaceAll("_", " ");
}

export function violationText(locale: Locale, violation: RuleViolation): string {
  const catalog = copy(locale).violations as Record<string, string>;
  const direct = catalog[violation.code];
  const aiMatch = violation.code.match(/^ai_(.+)_not_permitted$/);
  const aiBan = violation.code.match(/^ai_(.+)_prohibited$/);
  const grantedAi = violation.code.match(/^granted_ai_(.+)$/);
  const template = direct ?? (aiMatch || aiBan ? catalog[aiBan ? "ai_prohibited" : "ai_not_permitted"] : grantedAi ? catalog.granted_ai : undefined);
  if (!template) return violation.message;
  const params: Record<string, string | number> = { ...(violation.params ?? {}) };
  const aiKey = String(params.ai ?? aiMatch?.[1] ?? aiBan?.[1] ?? grantedAi?.[1] ?? "");
  if (aiKey) params.ai = term(locale, "ai", aiKey);
  if (typeof params.category === "string") params.category = term(locale, "categories", params.category);
  if (typeof params.channel === "string") params.channel = term(locale, "channels", params.channel);
  if (typeof params.territory === "string") params.territory = term(locale, "territories", params.territory);
  if (typeof params.status === "string") params.status = term(locale, "statuses", params.status);
  if (template.includes("{") && Object.keys(params).length === 0) return violation.message;
  return fill(template, params);
}

export function apiErrorText(locale: Locale, code: string, fallback: string): string {
  const known = copy(locale).errors as Record<string, string>;
  return known[code] ?? fallback;
}
